create table if not exists public.matches (
  id integer primary key,
  group_name text not null,
  match_time text not null,
  team_a text not null,
  team_b text not null,
  score_a integer not null default 0 check (score_a >= 0),
  score_b integer not null default 0 check (score_b >= 0),
  created_at timestamptz not null default now(),
  cup text,
  phase text,
  bracket_key text,
  next_match_id integer references public.matches(id),
  next_slot text
);

create table if not exists public.match_events (
  id bigint generated by default as identity primary key,
  match_id integer not null references public.matches(id) on delete cascade,
  team text not null,
  minute text not null,
  player text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.poll_options (
  id integer primary key,
  team text not null,
  votes integer not null default 0 check (votes >= 0)
);

create table if not exists public.votes (
  voter_hash text primary key,
  option_id integer not null references public.poll_options(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists match_events_match_id_idx on public.match_events (match_id);
create index if not exists votes_option_id_idx on public.votes (option_id);

alter table public.matches enable row level security;
alter table public.match_events enable row level security;
alter table public.poll_options enable row level security;
alter table public.votes enable row level security;

revoke all on public.matches, public.match_events, public.poll_options, public.votes from anon, authenticated;

