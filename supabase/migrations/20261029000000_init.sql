create or replace function public.vote_for_option(p_voter_hash text, p_option_id integer)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  existing_option_id integer;
begin
  if p_voter_hash is null or length(p_voter_hash) < 32 then
    return jsonb_build_object('status', 'invalid');
  end if;

  if not exists (select 1 from poll_options where id = p_option_id) then
    return jsonb_build_object('status', 'invalid');
  end if;

  select option_id into existing_option_id from votes where voter_hash = p_voter_hash;
  if found then
    return jsonb_build_object('status', 'already', 'optionId', existing_option_id);
  end if;

  insert into votes (voter_hash, option_id) values (p_voter_hash, p_option_id);
  update poll_options set votes = votes + 1 where id = p_option_id;
  return jsonb_build_object('status', 'ok', 'optionId', p_option_id);
exception
  when unique_violation then
    select option_id into existing_option_id from votes where voter_hash = p_voter_hash;
    return jsonb_build_object('status', 'already', 'optionId', existing_option_id);
end;
$$;

create or replace function public.adjust_score(p_match_id integer, p_team text, p_delta integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_team = 'A' then
    update matches set score_a = greatest(0, score_a + p_delta) where id = p_match_id;
  elsif p_team = 'B' then
    update matches set score_b = greatest(0, score_b + p_delta) where id = p_match_id;
  else
    raise exception 'invalid_team';
  end if;

  if not found then
    raise exception 'match_not_found';
  end if;
end;
$$;

create or replace function public.register_goal(
  p_match_id integer,
  p_team text,
  p_minute text,
  p_player text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  match_team_a text;
  match_team_b text;
begin
  select team_a, team_b into match_team_a, match_team_b
  from matches
  where id = p_match_id
  for update;

  if not found then
    raise exception 'match_not_found';
  end if;

  if p_team not in (match_team_a, match_team_b) then
    raise exception 'invalid_team';
  end if;

  insert into match_events (match_id, team, minute, player)
  values (p_match_id, p_team, p_minute, p_player);

  if p_team = match_team_a then
    update matches set score_a = score_a + 1 where id = p_match_id;
  else
    update matches set score_b = score_b + 1 where id = p_match_id;
  end if;
end;
$$;

